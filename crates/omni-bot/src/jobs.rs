/// Maximum continuation hops per attempt (each hop is ≤ the per-request output limit).
const MAX_HOPS: u32 = 64;
/// Maximum checkpoint resumes after stream drops within one attempt.
const MAX_RESUMES: u32 = 3;
/// Maximum automatic `max_tokens` reductions after context-overflow errors.
const MAX_SHRINKS: u32 = 3;

/// Start generating `turn_id` in the background (no-op if already running).
pub fn spawn_turn(app: Arc<App>, turn_id: i64) {
    spawn(app, turn_id, None);
}

/// Continue a turn that stopped at its long-decode budget (`/continue`
/// sent as message `command_msg`). Returns false if the turn is busy.
pub fn spawn_continue(app: Arc<App>, turn_id: i64, command_msg: i32) -> bool {
    spawn(app, turn_id, Some(command_msg))
}

fn spawn(app: Arc<App>, turn_id: i64, cont: Option<i32>) -> bool {
    if !app.running.lock().insert(turn_id) {
        return false;
    }
    tokio::spawn(async move {
        let span = info_span!("turn", turn = turn_id);
        let res = match cont {
            None => run_turn(app.clone(), turn_id).instrument(span).await,
            Some(msg) => run_continue(app.clone(), turn_id, msg).instrument(span).await,
        };
        if let Err(e) = res {
            error!(turn = turn_id, error = %format!("{e:#}"), "turn failed internally");
            let _ = conv::set_turn_status(&app.db, turn_id, TurnStatus::Failed).await;
        }
        app.running.lock().remove(&turn_id);
        let _ = app.turn_done.send(turn_id);
    });
    true
}

/// Resume everything that was in flight when the bot stopped.
pub async fn recover(app: Arc<App>) -> Result<()> {
    let turns = conv::unfinished_turns(&app.db).await?;
    if !turns.is_empty() {
        info!(count = turns.len(), "resuming unfinished generations");
    }
    for t in turns {
        spawn_turn(app.clone(), t);
    }
    Ok(())
}

fn show_usage(app: &App, usage: Option<&Usage>) -> bool {
    match app.cfg.render.show_usage.as_str() {
        "always" => true,
        "never" => false,
        t => match (t.parse::<f64>(), usage.and_then(|u| u.cost_usd)) {
            (Ok(th), Some(c)) => c >= th,
            _ => true,
        },
    }
}

async fn wait_for_ancestors(app: &App, turn_id: i64) -> Result<Result<Vec<TurnRow>, String>> {
    let mut rx = app.turn_done.subscribe();
    loop {
        let hist = conv::history(&app.db, turn_id).await?;
        let mut blocking = None;
        for t in &hist[..hist.len().saturating_sub(1)] {
            if t.turn.role == Role::Assistant {
                match t.status {
                    TurnStatus::Failed => {
                        return Ok(Err("the message this conversation continues from failed to generate".into()));
                    }
                    TurnStatus::Pending | TurnStatus::Running => blocking = Some(t.id),
                    TurnStatus::Done => {}
                }
            }
        }
        if blocking.is_none() {
            return Ok(Ok(hist));
        }
        let _ = tokio::time::timeout(Duration::from_secs(10), async {
            loop {
                match rx.recv().await {
                    Ok(id) if Some(id) == blocking => break,
                    Ok(_) => {}
                    Err(_) => break,
                }
            }
        })
        .await;
    }
}

/// Exact token count of the conversation prefix ending at the latest assistant
/// turn generated by the same model (from its reported usage).
fn known_context(history: &[Turn], model: &str) -> Option<KnownContext> {
    history.iter().enumerate().rev().find_map(|(i, t)| {
        let n = t.native.as_ref()?;
        (t.role == Role::Assistant && n.model == model).then_some(())?;
        Some(KnownContext { upto: i + 1, tokens: n.context_tokens? })
    })
}

/// A persisted resume point inside an attempt (long decode).
#[derive(Debug, Clone, Serialize, Deserialize)]
struct Checkpoint {
    /// Continuation item to resend.
    item: Value,
    /// Accumulated parts at the moment the item arrived.
    parts: Vec<Part>,
    /// Usage of completed hops.
    #[serde(default)]
    usage: Option<Usage>,
    #[serde(default)]
    hops: u32,
    /// Prompt tokens of the first hop (for context accounting).
    #[serde(default)]
    first_prompt: Option<u64>,
    /// Native payloads of completed hops.
    #[serde(default)]
    natives: Vec<Value>,
    /// True if this checkpoint ended the attempt at the budget (`/continue` possible).
    #[serde(default)]
    at_budget: bool,
    /// True inside a `/continue` attempt: `parts` hold only the newly appended output.
    #[serde(default)]
    append: bool,
    /// Output tokens of the whole turn so far, across hops and `/continue`s
    /// (the long-decode budget is cumulative).
    #[serde(default)]
    spent: u64,
    /// Budget added by each `/continue` (the turn's first `max_tokens`).
    #[serde(default)]
    step: u64,
}

/// OpenRouter's output budget when `max_tokens` is omitted.
const DEFAULT_BUDGET: u64 = 65_536;

/// Force `max_tokens` (continuations must resend the same cumulative budget, or raise it).
fn force_max_tokens(p: &mut Prepared, v: Option<u64>, source: &str) {
    match v {
        Some(v) => {
            if p.max_tokens() != Some(v) {
                p.body["max_tokens"] = json!(v);
                p.applied.push(omni_llm::openrouter::options::Applied {
                    source: source.into(),
                    patch: json!({"max_tokens": v}),
                });
            }
        }
        None => {
            if let Some(o) = p.body.as_object_mut() {
                o.remove("max_tokens");
            }
        }
    }
    p.auto_max_tokens = None;
}

/// Google's 400 when a resumed hop has no budget left (the dropped hop spent it).
fn budget_exhausted(e: &LlmError) -> bool {
    let mut s = e.message.to_ascii_lowercase();
    if let Some(d) = &e.details {
        s.push_str(&d.to_string().to_ascii_lowercase());
    }
    s.contains("exhausted") && (s.contains("max_output_tokens") || s.contains("max_tokens"))
}

async fn save_checkpoint(app: &App, attempt_id: i64, cp: Option<&Checkpoint>) {
    let s = cp.and_then(|c| serde_json::to_string(c).ok());
    let _ = app
        .db
        .call(move |c| {
            c.execute("UPDATE attempts SET checkpoint = ?1 WHERE id = ?2", params![s, attempt_id])?;
            Ok(())
        })
        .await;
}

async fn load_checkpoint(app: &App, attempt_id: i64) -> Option<Checkpoint> {
    let s: Option<String> = app
        .db
        .call(move |c| {
            Ok(c.query_row("SELECT checkpoint FROM attempts WHERE id = ?1", params![attempt_id], |r| r.get(0))
                .optional()?
                .flatten())
        })
        .await
        .ok()
        .flatten();
    s.and_then(|s| serde_json::from_str(&s).ok())
}

/// Everything an attempt needs.
struct Ctx {
    app: Arc<App>,
    bot: Arc<BotConn>,
    chat_id: i64,
    user_id: i64,
    turn_id: i64,
    reply_to: Option<i32>,
    spec: ResolvedSpec,
    history: Vec<Turn>,
    root: i64,
    base_state: RenderState,
    max_attempts: u32,
}

impl Ctx {
    async fn prepare(&self, max_tokens_override: Option<u64>) -> Result<Prepared, LlmError> {
        let presets = self.app.presets_for(&self.spec.canonical());
        let input = CallInput {
            model: &self.spec.model,
            options: &self.spec.options,
            history: &self.history,
            session_id: Some(format!("tg-{}", self.root)),
            user: self.app.user_hash(self.user_id),
            known_context: known_context(&self.history, &self.spec.model),
            max_tokens_override,
        };
        let blobs = Blobs(self.app.blobs.clone());
        match self.spec.provider.as_str() {
            "ark" => match &self.app.ark {
                Some(ark) => ark.prepare_chat(&input, &presets, &blobs).await,
                None => Err(LlmError::request(
                    "the Volcengine Ark provider is not configured (set ARK_API_KEY / [providers.ark] api_key)",
                )),
            },
            _ => self.app.openrouter.prepare_chat(&input, &presets, &blobs).await,
        }
    }

    fn call_meta(&self, attempt_id: i64) -> crate::ledger::CallMeta {
        crate::ledger::CallMeta {
            bot: self.bot.name.clone(),
            chat_id: self.chat_id,
            user_id: self.user_id,
            turn_id: self.turn_id,
            attempt_id,
            provider: self.spec.provider.clone(),
            model: self.spec.model.clone(),
        }
    }

    fn request_record(&self, p: &Prepared) -> Value {
        let body = omni_core::json::redact_blobs(&p.body, &mut |b, m| {
            self.app.blobs.put_sync(b, m).unwrap_or_else(|_| omni_core::BlobRef::for_bytes(b, m))
        });
        json!({
            "dialect": p.dialect,
            "url": p.url,
            "body": body,
            "auto_max_tokens": p.auto_max_tokens,
            "applied": p.applied.iter().map(|a| json!({"source": a.source, "patch": a.patch})).collect::<Vec<_>>(),
        })
    }
}

/// Where an attempt starts.
enum Start {
    Fresh,
    /// Resume the same attempt from its checkpoint (bot restarted mid long decode).
    Resume(Checkpoint),
    /// `/continue`: resume a finished turn from its final continuation item;
    /// only the new output is shown in new messages and appended to the turn.
    Append(Checkpoint),
}

/// Whether `/continue` can extend this turn (it stopped at its long-decode budget).
pub async fn can_continue(app: &App, turn_id: i64) -> Result<bool> {
    let attempts = conv::attempts_of(&app.db, turn_id).await?;
    let Some(last) = attempts.iter().rev().find(|a| a.status == "done") else { return Ok(false) };
    Ok(load_checkpoint(app, last.id).await.is_some_and(|c| c.at_budget))
}

enum Outcome {
    Done,
    Failed,
    Retry(Duration),
    Shrink(u64),
    Shutdown,
}

async fn load_ctx(app: &Arc<App>, row: &TurnRow) -> Result<Option<(Ctx, Vec<TurnRow>)>> {
    let spec = row.spec.clone().context("assistant turn without spec")?;
    let bot_name = row.bot.clone().context("turn without bot")?;
    let bot = app.bot(&bot_name).cloned().ok_or_else(|| anyhow!("bot {bot_name} is not configured any more"))?;
    let chat_id = row.chat_id.context("turn without chat")?;
    let user_id = row.user_id.unwrap_or(0);
    let reply_to = match row.inbound_id {
        Some(i) => conv::get_inbound(&app.db, i).await.ok().map(|i| i.msg_id),
        None => None,
    };
    let max_attempts = app.cfg.retry.max_attempts.max(1);
    let base_state = RenderState {
        model: spec.model.clone(),
        options: spec.options_syntax(),
        parts: Vec::new(),
        status: Status::Generating,
        attempt: 1,
        max_attempts,
        error: None,
        usage: None,
        provider: None,
        finish_reason: None,
        native_finish_reason: None,
        notes: Vec::new(),
        started: Instant::now(),
        elapsed_override: None,
        images: 0,
        hops: 0,
        continuation: false,
        show_usage: true,
        mode: app.cfg.render.markdown,
        done: false,
    };
    let hist = match wait_for_ancestors(app, row.id).await? {
        Ok(h) => h,
        Err(msg) => {
            let ctx = Ctx {
                app: app.clone(),
                bot,
                chat_id,
                user_id,
                turn_id: row.id,
                reply_to,
                spec,
                history: vec![],
                root: row.id,
                base_state,
                max_attempts,
            };
            fail_without_attempt(&ctx, LlmError::request(msg)).await?;
            return Ok(None);
        }
    };
    let history: Vec<Turn> = hist[..hist.len() - 1].iter().map(|t| t.turn.clone()).collect();
    let root = hist.first().map(|t| t.id).unwrap_or(row.id);
    Ok(Some((
        Ctx {
            app: app.clone(),
            bot,
            chat_id,
            user_id,
            turn_id: row.id,
            reply_to,
            spec,
            history,
            root,
            base_state,
            max_attempts,
        },
        hist,
    )))
}

async fn run_turn(app: Arc<App>, turn_id: i64) -> Result<()> {
    let row = conv::get_turn(&app.db, turn_id).await?;
    if row.status.is_finished() {
        return Ok(());
    }
    let Some((ctx, _)) = load_ctx(&app, &row).await? else { return Ok(()) };
    let span = info_span!("conv", bot = %ctx.bot.name, chat = ctx.chat_id, user = ctx.user_id, model = %ctx.spec.model);
    async move {
        let attempts = conv::attempts_of(&app.db, turn_id).await?;
        // An attempt interrupted by a restart: resume it in place if it has a checkpoint.
        if let Some(last) = attempts.last().filter(|a| a.status == "running") {
            let (req, ..) = conv::attempt_json(&app.db, last.id).await?;
            let appending = req.as_ref().and_then(|r| r.get("continue")).and_then(Value::as_bool).unwrap_or(false);
            let max_tokens = req.as_ref().and_then(|r| r.pointer("/body/max_tokens")).and_then(Value::as_u64);
            if let Some(cp) = load_checkpoint(&app, last.id).await.filter(|c| !c.at_budget) {
                warn!(
                    attempt = last.n,
                    hops = cp.hops,
                    append = cp.append,
                    "resuming interrupted attempt from its checkpoint"
                );
                match ctx.prepare(None).await {
                    Ok(mut p) => {
                        // Resend the interrupted request's budget unchanged (it is cumulative across hops).
                        force_max_tokens(&mut p, max_tokens, "resume");
                        let append = cp.append;
                        let out = run_attempt(&ctx, &p, last, Start::Resume(cp), 0).await;
                        match out {
                            Outcome::Done | Outcome::Shutdown => return Ok(()),
                            _ if append => {
                                // The output before `/continue` is still valid.
                                conv::set_turn_status(&app.db, turn_id, TurnStatus::Done).await?;
                                return Ok(());
                            }
                            Outcome::Failed => {
                                conv::set_turn_status(&app.db, turn_id, TurnStatus::Failed).await?;
                                return Ok(());
                            }
                            Outcome::Retry(_) | Outcome::Shrink(_) => {}
                        }
                    }
                    Err(e) => {
                        warn!(error = %e, "cannot rebuild the request to resume");
                        mark_interrupted(&ctx, last, appending).await?;
                        if appending {
                            conv::set_turn_status(&app.db, turn_id, TurnStatus::Done).await?;
                            return Ok(());
                        }
                    }
                }
            } else {
                mark_interrupted(&ctx, last, appending).await?;
                if appending {
                    conv::set_turn_status(&app.db, turn_id, TurnStatus::Done).await?;
                    return Ok(());
                }
            }
        }
        let attempts = conv::attempts_of(&app.db, turn_id).await?;
        let mut failed = attempts.iter().filter(|a| a.status == "failed").count() as u32;
        let mut shrinks = 0;
        let mut override_max = None;
        loop {
            if let Err(msg) = crate::access::check_quota(&app, ctx.chat_id, ctx.user_id).await? {
                fail_without_attempt(&ctx, LlmError::request(msg)).await?;
                return Ok(());
            }
            let prepared = match ctx.prepare(override_max).await {
                Ok(p) => p,
                Err(e) => {
                    fail_without_attempt(&ctx, e).await?;
                    return Ok(());
                }
            };
            let attempt = conv::start_attempt(&app.db, turn_id, &ctx.request_record(&prepared)).await?;
            match run_attempt(&ctx, &prepared, &attempt, Start::Fresh, failed).await {
                Outcome::Done | Outcome::Shutdown => return Ok(()),
                Outcome::Failed => {
                    conv::set_turn_status(&app.db, turn_id, TurnStatus::Failed).await?;
                    return Ok(());
                }
                Outcome::Shrink(v) if shrinks < MAX_SHRINKS => {
                    shrinks += 1;
                    override_max = Some(v);
                    info!(max_tokens = v, "context overflow: retrying immediately with a smaller max_tokens");
                }
                Outcome::Shrink(_) => {
                    conv::set_turn_status(&app.db, turn_id, TurnStatus::Failed).await?;
                    return Ok(());
                }
                Outcome::Retry(d) => {
                    failed += 1;
                    tokio::select! {
                        _ = tokio::time::sleep(d) => {}
                        _ = app.shutdown.cancelled() => return Ok(()),
                    }
                }
            }
        }
    }
    .instrument(span)
    .await
}

/// `/continue`: resume a finished long-decode turn past its budget.
async fn run_continue(app: Arc<App>, turn_id: i64, command_msg: i32) -> Result<()> {
    let row = conv::get_turn(&app.db, turn_id).await?;
    if row.status != TurnStatus::Done {
        return Ok(());
    }
    let Some((ctx, _)) = load_ctx(&app, &row).await? else { return Ok(()) };
    let attempts = conv::attempts_of(&app.db, turn_id).await?;
    let Some(last_done) = attempts.iter().rev().find(|a| a.status == "done") else { return Ok(()) };
    let Some(cp) = load_checkpoint(&app, last_done.id).await.filter(|c| c.at_budget) else { return Ok(()) };
    let span = info_span!("conv", bot = %ctx.bot.name, chat = ctx.chat_id, user = ctx.user_id, model = %ctx.spec.model);
    async move {
        if let Err(msg) = crate::access::check_quota(&app, ctx.chat_id, ctx.user_id).await? {
            crate::reply::notice(&app, &ctx.bot, ctx.chat_id, command_msg, &format!("⚠️ {msg}")).await;
            return Ok(());
        }
        let step = if cp.step > 0 { cp.step } else { app.openrouter.config().fidelity.long_decode_budget };
        let budget = cp.spent + step;
        let mut prepared = match ctx.prepare(None).await {
            Ok(p) => p,
            Err(e) => {
                crate::reply::notice(&app, &ctx.bot, ctx.chat_id, command_msg, &format!("⚠️ {e}")).await;
                return Ok(());
            }
        };
        // The budget is cumulative: it must exceed everything generated so far.
        force_max_tokens(&mut prepared, Some(budget), "continue");
        let mut rec = ctx.request_record(&prepared);
        rec["continue"] = json!(true);
        conv::set_turn_status(&app.db, turn_id, TurnStatus::Running).await?;
        let attempt = conv::start_attempt(&app.db, turn_id, &rec).await?;
        info!(spent = cp.spent, max_tokens = budget, "continuing past the long-decode budget");
        match run_attempt(&ctx, &prepared, &attempt, Start::Append(cp), 0).await {
            Outcome::Done | Outcome::Shutdown => {}
            // The output before `/continue` stays valid.
            _ => conv::set_turn_status(&app.db, turn_id, TurnStatus::Done).await?,
        }
        Ok(())
    }
    .instrument(span)
    .await
}

async fn mark_interrupted(ctx: &Ctx, last: &AttemptRow, appending: bool) -> Result<()> {
    let app = &ctx.app;
    warn!(attempt = last.n, "attempt was interrupted by a restart");
    let (_, out, _, upstream, _) = conv::attempt_json(&app.db, last.id).await?;
    let mut parts: Vec<Part> =
        out.and_then(|o| serde_json::from_value::<Turn>(o).ok()).map(|t| t.parts).unwrap_or_default();
    // The last seconds of output may not have been persisted: OpenRouter can return
    // what it had delivered before the disconnect (if Input & Output Logging is on).
    // (The stored id list is comma-separated; the last call is the interrupted one.)
    let last_id = upstream.as_deref().and_then(|u| u.rsplit(',').next()).filter(|s| !s.is_empty());
    if let Some(gen_id) = last_id.filter(|_| ctx.spec.provider == "openrouter")
        && let Some(recovered) = recover_delivered(app, gen_id).await
    {
        let have: usize = parts.iter().map(|p| if let Part::Text { text, .. } = p { text.len() } else { 0 }).sum();
        let got: usize = recovered.iter().map(|p| if let Part::Text { text, .. } = p { text.len() } else { 0 }).sum();
        if got > have {
            parts = recovered;
        }
    }
    conv::update_attempt(
        &app.db,
        last.id,
        AttemptUpdate {
            status: "interrupted",
            output: serde_json::to_value(Turn {
                role: Role::Assistant,
                origin: Default::default(),
                parts: parts.clone(),
                native: None,
            })
            .ok(),
            error: Some(json!({"message": "interrupted by bot restart"})),
            upstream_id: None,
            usage: None,
            finished: true,
        },
    )
    .await?;
    let view =
        ReplyView::start(app.clone(), ctx.bot.clone(), ctx.chat_id, ctx.reply_to, ctx.turn_id, last.id, Duration::ZERO);
    let mut st = ctx.base_state.clone();
    st.parts = parts;
    st.attempt = last.n;
    st.elapsed_override = Some(Duration::ZERO);
    if appending {
        st.status = Status::Failed;
        st.error = Some(LlmError::request(
            "interrupted by a bot restart; reply /continue to the previous message to try again",
        ));
    } else {
        st.status = Status::Interrupted;
    }
    view.finish(st).await;
    Ok(())
}

/// Output delivered before a disconnect, from OpenRouter's stored content.
async fn recover_delivered(app: &App, gen_id: &str) -> Option<Vec<Part>> {
    for _ in 0..4 {
        match app.openrouter.generation_content(gen_id).await {
            Ok(Some(d)) => {
                let out = d.get("output")?;
                let mut parts = Vec::new();
                if let Some(r) = out.get("reasoning").and_then(Value::as_str).filter(|s| !s.is_empty()) {
                    parts.push(Part::Reasoning(omni_core::Reasoning {
                        kind: ReasoningKind::Text,
                        text: Some(r.into()),
                        ..Default::default()
                    }));
                }
                if let Some(c) = out.get("completion").and_then(Value::as_str).filter(|s| !s.is_empty()) {
                    parts.push(Part::text(c));
                }
                return Some(parts);
            }
            Ok(None) => tokio::time::sleep(Duration::from_secs(4)).await,
            Err(e) => {
                warn!(error = %format!("{e:#}"), "generation content lookup failed");
                return None;
            }
        }
    }
    None
}

fn backoff(app: &App, failed: u32, e: &LlmError) -> Option<Duration> {
    let base = app.cfg.retry.base_delay_secs * 2f64.powi(failed.saturating_sub(1) as i32);
    let base = Duration::from_secs_f64(base.min(app.cfg.retry.max_delay_secs));
    e.retry_delay(base)
}

fn add_usage(a: &Option<Usage>, b: &Usage) -> Usage {
    let Some(a) = a else { return b.clone() };
    let s = |x: Option<u64>, y: Option<u64>| match (x, y) {
        (None, None) => None,
        (x, y) => Some(x.unwrap_or(0) + y.unwrap_or(0)),
    };
    Usage {
        input_tokens: s(a.input_tokens, b.input_tokens),
        output_tokens: s(a.output_tokens, b.output_tokens),
        reasoning_tokens: s(a.reasoning_tokens, b.reasoning_tokens),
        cached_input_tokens: s(a.cached_input_tokens, b.cached_input_tokens),
        cache_write_tokens: s(a.cache_write_tokens, b.cache_write_tokens),
        cost_usd: match (a.cost_usd, b.cost_usd) {
            (None, None) => None,
            (x, y) => Some(x.unwrap_or(0.0) + y.unwrap_or(0.0)),
        },
        cost_source: b.cost_source,
        raw: {
            let mut v = match &a.raw {
                Value::Array(x) => x.clone(),
                Value::Null => vec![],
                other => vec![other.clone()],
            };
            v.push(b.raw.clone());
            Value::Array(v)
        },
    }
}

struct Sink<'a> {
    acc: Accumulator,
    view: &'a ReplyView,
    state: RenderState,
    last_save: Instant,
    last_push: Instant,
    app: &'a App,
    attempt_id: i64,
    /// Usage of completed hops; the current hop's usage is added on top.
    usage_done: Option<Usage>,
    hop_usage: Option<Usage>,
    first_prompt: Option<u64>,
    hops: u32,
    natives: Vec<Value>,
    /// Latest resume point of the current hop: (item, parts at that moment).
    checkpoint: Option<(Value, Vec<Part>)>,
    /// Inside a `/continue` attempt.
    append: bool,
    /// Output tokens of the turn before this attempt (`/continue`).
    spent_before: u64,
    /// Budget step for `/continue`.
    step: u64,
    /// Generation id already registered as a pending call.
    registered: Option<String>,
    /// Calls of this provider can be looked up afterwards (OpenRouter `/generation`).
    lookup_costs: bool,
}

impl Sink<'_> {
    fn render(&self) -> RenderState {
        let mut s = self.state.clone();
        s.parts = self.acc.parts().to_vec();
        s.usage = self.total_usage();
        s.provider = self.acc.provider.clone();
        s.finish_reason = self.acc.finish_reason.clone();
        s.native_finish_reason = self.acc.native_finish_reason.clone();
        s.images = s.parts.iter().filter(|p| matches!(p, Part::Image { generated: true, .. })).count();
        s.hops = self.hops;
        for n in &self.acc.notices {
            if !s.notes.contains(n) {
                s.notes.push(n.clone());
            }
        }
        s
    }

    fn total_usage(&self) -> Option<Usage> {
        match (&self.usage_done, &self.hop_usage) {
            (u, Some(h)) => Some(add_usage(u, h)),
            (u, None) => u.clone(),
        }
    }

    /// Close the current hop: fold its usage (if it arrived) into the total.
    fn end_hop(&mut self) -> Option<Usage> {
        let h = self.hop_usage.take()?;
        if self.first_prompt.is_none() {
            self.first_prompt = h.input_tokens;
        }
        self.usage_done = Some(add_usage(&self.usage_done, &h));
        Some(h)
    }

    fn checkpoint_record(&self, item: Value, parts: Vec<Part>, at_budget: bool) -> Checkpoint {
        let spent = self.spent_before + self.usage_done.as_ref().and_then(|u| u.output_tokens).unwrap_or(0);
        Checkpoint {
            item,
            parts,
            usage: self.usage_done.clone(),
            hops: self.hops,
            first_prompt: self.first_prompt,
            natives: self.natives.clone(),
            at_budget,
            append: self.append,
            spent,
            step: self.step,
        }
    }
}

impl EventSink for Sink<'_> {
    fn event(&mut self, ev: StreamEvent) {
        match &ev {
            StreamEvent::Usage(u) => {
                self.hop_usage = Some(u.clone());
                return;
            }
            StreamEvent::Meta { upstream_id: Some(id), .. }
                if self.lookup_costs && self.registered.as_ref() != Some(id) =>
            {
                // Billed from now on: make sure the cost is found even if the stream never finishes.
                self.registered = Some(id.clone());
                let (db, id, attempt) = (self.app.db.clone(), id.clone(), self.attempt_id);
                tokio::spawn(async move { crate::ledger::begin_call(&db, id, attempt).await });
            }
            StreamEvent::Checkpoint(item) => {
                let parts = self.acc.parts().to_vec();
                self.checkpoint = Some((item.clone(), parts.clone()));
                let cp = self.checkpoint_record(item.clone(), parts, false);
                let (app, id) = (self.app, self.attempt_id);
                let s = serde_json::to_string(&cp).ok();
                let db = app.db.clone();
                tokio::spawn(async move {
                    let _ = db
                        .call(move |c| {
                            c.execute("UPDATE attempts SET checkpoint = ?1 WHERE id = ?2", params![s, id])?;
                            Ok(())
                        })
                        .await;
                });
                return;
            }
            _ => {}
        }
        let is_image = matches!(ev, StreamEvent::Image { .. });
        self.acc.apply(ev);
        if is_image {
            for (data, mime) in self.acc.take_pending_images() {
                match self.app.blobs.put_sync(&data, &mime) {
                    Ok(b) => self.acc.attach_image(b),
                    Err(e) => warn!(error = %e, "failed to store generated image"),
                }
            }
        }
        if self.last_push.elapsed() >= Duration::from_millis(250) {
            self.last_push = Instant::now();
            self.view.update(self.render());
        }
        if self.last_save.elapsed() > Duration::from_secs(10) {
            self.last_save = Instant::now();
            let (db, id, out) = (self.app.db.clone(), self.attempt_id, serde_json::to_value(self.acc.turn()).ok());
            tokio::spawn(async move {
                let _ = conv::update_attempt(
                    &db,
                    id,
                    AttemptUpdate {
                        status: "running",
                        output: out,
                        error: None,
                        upstream_id: None,
                        usage: None,
                        finished: false,
                    },
                )
                .await;
            });
        }
    }
}

/// Run one upstream call with the turn's provider.
async fn stream(
    app: &App,
    provider: &str,
    p: &Prepared,
    sink: &mut dyn EventSink,
    observer: &RawLog,
    cancel: &CancellationToken,
) -> (Result<Value, LlmError>, omni_llm::CallOutcome) {
    match (provider, &app.ark) {
        ("ark", Some(ark)) => ark.stream_chat(p, sink, observer, cancel).await,
        ("ark", None) => (Err(LlmError::request("the Volcengine Ark provider is not configured")), Default::default()),
        _ => app.openrouter.stream_chat(p, sink, observer, cancel).await,
    }
}

/// Merge the native payloads of several hops into one assistant message for replay.
fn merge_natives(natives: &[Value], full_text: &str) -> Value {
    let mut m = natives.last().cloned().unwrap_or_else(|| json!({"role": "assistant"}));
    m["content"] = json!(full_text);
    let details: Vec<Value> = natives
        .iter()
        .filter_map(|n| n.get("reasoning_details").and_then(Value::as_array))
        .flatten()
        .cloned()
        .collect();
    if !details.is_empty() {
        m["reasoning_details"] = Value::Array(details);
    }
    let reasoning: String = natives.iter().filter_map(|n| n.get("reasoning").and_then(Value::as_str)).collect();
    if !reasoning.is_empty() {
        m["reasoning"] = json!(reasoning);
    }
    m
}

async fn run_attempt(
    ctx: &Ctx,
    prepared: &Prepared,
    attempt: &AttemptRow,
    start: Start,
    failed_before: u32,
) -> Outcome {
    let app = &ctx.app;
    let attempt_span = info_span!("attempt", n = attempt.n, id = attempt.id);
    async move {
        info!(
            applied = ?prepared.applied.iter().map(|a| a.source.as_str()).collect::<Vec<_>>(),
            max_tokens = ?prepared.max_tokens(),
            long_decode = prepared.long_decode,
            "starting attempt"
        );
        let mut state = ctx.base_state.clone();
        state.attempt = attempt.n;
        state.started = Instant::now();
        state.notes = prepared.warnings.iter().chain(prepared.notes.iter()).cloned().collect();
        let append_mode = match &start {
            Start::Append(_) => true,
            Start::Resume(cp) => cp.append,
            Start::Fresh => false,
        };
        // `/continue`: the turn as it was before, and the reply target for the new messages.
        let (old_turn, reply_to) = if append_mode {
            let row = conv::get_turn(&app.db, ctx.turn_id).await.ok();
            let last_msg = last_message_of_turn(app, ctx.turn_id, attempt.id).await;
            (row.map(|r| r.turn), last_msg.or(ctx.reply_to))
        } else {
            (None, ctx.reply_to)
        };
        state.continuation = append_mode;
        let first_delay = Duration::from_secs_f64(app.cfg.render.first_flush_delay_secs);
        let view =
            ReplyView::start(app.clone(), ctx.bot.clone(), ctx.chat_id, reply_to, ctx.turn_id, attempt.id, first_delay);
        let mut sink = Sink {
            acc: Accumulator::new(),
            view: &view,
            state: state.clone(),
            last_save: Instant::now(),
            last_push: Instant::now() - Duration::from_secs(1),
            app,
            attempt_id: attempt.id,
            usage_done: None,
            hop_usage: None,
            first_prompt: None,
            hops: 0,
            natives: vec![],
            checkpoint: None,
            append: append_mode,
            spent_before: 0,
            step: prepared.max_tokens().unwrap_or(DEFAULT_BUDGET),
            registered: None,
            lookup_costs: ctx.spec.provider == "openrouter",
        };
        let mut hop_req = prepared.clone();
        match &start {
            Start::Fresh => {}
            Start::Resume(cp) => {
                sink.acc.restore_parts(cp.parts.clone());
                sink.usage_done = cp.usage.clone();
                sink.hops = cp.hops;
                sink.first_prompt = cp.first_prompt;
                sink.natives = cp.natives.clone();
                sink.spent_before =
                    cp.spent - cp.usage.as_ref().and_then(|u| u.output_tokens).unwrap_or(0).min(cp.spent);
                if cp.step > 0 {
                    sink.step = cp.step;
                }
                sink.checkpoint = Some((cp.item.clone(), cp.parts.clone()));
                hop_req = prepared.with_continuation(&cp.item);
            }
            Start::Append(cp) => {
                sink.first_prompt = cp.first_prompt;
                sink.spent_before = cp.spent;
                if cp.step > 0 {
                    sink.step = cp.step;
                }
                hop_req = prepared.with_continuation(&cp.item);
            }
        }
        view.update(sink.render());
        let rawlog = RawLog { blobs: app.blobs.clone() };
        let mut resumes = 0u32;
        let mut upstream_ids: Vec<String> = Vec::new();
        let result: Result<bool, LlmError> = loop {
            sink.acc.finish_reason = None;
            sink.acc.native_finish_reason = None;
            sink.acc.upstream_id = None;
            let cancel = CancellationToken::new();
            let (result, call) = tokio::select! {
                r = stream(app, &ctx.spec.provider, &hop_req, &mut sink, &rawlog, &cancel) => r,
                _ = app.shutdown.cancelled() => (Err(LlmError::cancelled()), Default::default()),
            };
            let hop_id = sink.acc.upstream_id.clone().or(call.upstream_id.clone());
            if let Some(id) = &hop_id
                && !upstream_ids.contains(id)
            {
                upstream_ids.push(id.clone());
            }
            if !call.upstream_echo.is_empty() {
                let echo = omni_core::json::redact_blobs(&Value::Array(call.upstream_echo.clone()), &mut |b, m| {
                    app.blobs.put_sync(b, m).unwrap_or_else(|_| omni_core::BlobRef::for_bytes(b, m))
                });
                tracing::debug!(target: "raw", echo = %echo, "upstream body echoed by OpenRouter");
                let _ = save_echo(app, attempt.id, echo).await;
            }
            if matches!(&result, Err(e) if e.kind == omni_llm::ErrorKind::Cancelled) && app.shutdown.is_cancelled() {
                // Leave the attempt "running": it is resumed (from its checkpoint, if any) after restart.
                let out = serde_json::to_value(sink.acc.turn()).ok();
                let up = Some(upstream_ids.join(",")).filter(|s| !s.is_empty());
                let _ = conv::update_attempt(
                    &app.db,
                    attempt.id,
                    AttemptUpdate {
                        status: "running",
                        output: out,
                        error: None,
                        upstream_id: up,
                        usage: None,
                        finished: false,
                    },
                )
                .await;
                return Outcome::Shutdown;
            }
            if let Some(u) = sink.end_hop() {
                let meta = ctx.call_meta(attempt.id);
                if let Err(e) = crate::ledger::record_call(&app.db, &meta, hop_id.clone(), &u, "reported").await {
                    warn!(error = %format!("{e:#}"), "failed to record usage");
                }
            }
            match result {
                Ok(native) => {
                    sink.natives.push(native);
                    let fr = sink.acc.finish_reason.clone();
                    let nfr = sink.acc.native_finish_reason.clone();
                    let can_continue =
                        prepared.long_decode && fr.as_deref() == Some("length") && call.continuation.is_some();
                    if can_continue && nfr.as_deref() == Some("CONTINUATION") && sink.hops < MAX_HOPS {
                        // Budget left: next hop resumes from the continuation item.
                        let item = call.continuation.clone().unwrap();
                        sink.hops += 1;
                        let cp = sink.checkpoint_record(item.clone(), sink.acc.parts().to_vec(), false);
                        save_checkpoint(app, attempt.id, Some(&cp)).await;
                        sink.checkpoint = Some((item.clone(), sink.acc.parts().to_vec()));
                        info!(hop = sink.hops, "long decode: continuing");
                        hop_req = prepared.with_continuation(&item);
                        sink.view.update(sink.render());
                        continue;
                    }
                    // Done. Remember the final continuation item when stopped at the budget (`/continue`).
                    let cp = can_continue.then(|| {
                        sink.checkpoint_record(call.continuation.clone().unwrap(), sink.acc.parts().to_vec(), true)
                    });
                    save_checkpoint(app, attempt.id, cp.as_ref()).await;
                    break Ok(cp.is_some());
                }
                Err(e) => {
                    if let Some((item, parts)) = sink.checkpoint.clone().filter(|_| budget_exhausted(&e)) {
                        // A dropped hop had already spent the budget: keep the output up to the
                        // checkpoint; `/continue` raises the budget.
                        warn!(error = %e, "budget exhausted while resuming; stopping at the checkpoint");
                        sink.acc.restore_parts(parts.clone());
                        sink.acc.finish_reason = Some("length".into());
                        sink.acc.native_finish_reason = Some("MAX_TOKENS".into());
                        let cp = sink.checkpoint_record(item, parts, true);
                        save_checkpoint(app, attempt.id, Some(&cp)).await;
                        break Ok(true);
                    }
                    let resumable = e.is_retryable() && e.kind != omni_llm::ErrorKind::Cancelled;
                    if resumable
                        && resumes < MAX_RESUMES
                        && let Some((item, parts)) = sink.checkpoint.clone()
                    {
                        resumes += 1;
                        warn!(error = %e, resume = resumes, "stream dropped; resuming from the latest checkpoint");
                        sink.acc.restore_parts(parts);
                        hop_req = prepared.with_continuation(&item);
                        continue;
                    }
                    break Err(e);
                }
            }
        };

        // Store generated images (if any are still pending).
        for (data, mime) in sink.acc.take_pending_images() {
            if let Ok(b) = app.blobs.put(data, mime).await {
                sink.acc.attach_image(b);
            }
        }
        let usage = sink.total_usage();
        let mut final_state = sink.render();
        final_state.show_usage = show_usage(app, usage.as_ref());
        let hops = sink.hops;
        let spent_before = sink.spent_before;
        let natives = std::mem::take(&mut sink.natives);
        let first_prompt = sink.first_prompt;
        let acc = sink.acc;
        match result {
            Ok(at_budget) => {
                let mut turn = acc.turn();
                let mut all_natives = natives;
                let mut spent_total = usage.as_ref().and_then(|u| u.output_tokens).unwrap_or(0);
                if let Some(old) = &old_turn {
                    // `/continue`: the turn keeps its earlier output; the new output is appended.
                    let mut parts = old.parts.clone();
                    for p in turn.parts.drain(..) {
                        match (parts.last_mut(), p) {
                            (Some(Part::Text { text, .. }), Part::Text { text: t, .. }) => text.push_str(&t),
                            (_, p) => parts.push(p),
                        }
                    }
                    turn.parts = parts;
                    if let Some(n) = &old.native {
                        all_natives.insert(0, n.payload.clone());
                    }
                }
                spent_total += spent_before;
                let full_text = turn.answer_text();
                turn.native = Some(omni_core::NativeOutput {
                    dialect: prepared.dialect.to_string(),
                    model: prepared.model.clone(),
                    payload: merge_natives(&all_natives, &full_text),
                    context_tokens: first_prompt.map(|p| p + spent_total),
                });
                if at_budget {
                    final_state.notes.push(format!(
                        "reached the long-decode output budget ({} tokens so far); reply /continue to keep writing",
                        spent_total
                    ));
                }
                conv::update_turn(&app.db, ctx.turn_id, &turn, TurnStatus::Done).await.ok();
                conv::update_attempt(
                    &app.db,
                    attempt.id,
                    AttemptUpdate {
                        status: "done",
                        output: serde_json::to_value(&turn).ok(),
                        error: None,
                        upstream_id: Some(upstream_ids.join(",")).filter(|s| !s.is_empty()),
                        usage: usage.as_ref().and_then(|u| serde_json::to_value(u).ok()),
                        finished: true,
                    },
                )
                .await
                .ok();
                final_state.status = Status::Done;
                final_state.done = true;
                let ids = view.finish(final_state).await;
                send_images(
                    app,
                    &ctx.bot,
                    ctx.chat_id,
                    ids.first().copied().or(reply_to),
                    ctx.turn_id,
                    attempt.id,
                    &acc.turn(),
                )
                .await;
                info!(cost = ?usage.as_ref().and_then(|u| u.cost_usd), hops, "attempt succeeded");
                Outcome::Done
            }
            Err(e) => {
                warn!(error = %e, retry = ?e.retry, "attempt failed");
                let turn = acc.turn();
                conv::update_attempt(
                    &app.db,
                    attempt.id,
                    AttemptUpdate {
                        status: "failed",
                        output: serde_json::to_value(&turn).ok(),
                        error: serde_json::to_value(&e).ok(),
                        upstream_id: Some(upstream_ids.join(",")).filter(|s| !s.is_empty()),
                        usage: usage.as_ref().and_then(|u| serde_json::to_value(u).ok()),
                        finished: true,
                    },
                )
                .await
                .ok();
                // Context overflow with an automatic max_tokens: shrink and retry at once.
                if !append_mode
                    && e.is_context_overflow()
                    && !acc.has_output()
                    && let Some(prev) = prepared.auto_max_tokens
                {
                    let msg =
                        format!("{} {}", e.message, e.details.as_ref().map(|d| d.to_string()).unwrap_or_default());
                    if let Some(v) = shrink_after_overflow(prev, &msg) {
                        final_state.error = Some(e.clone());
                        final_state.status = Status::Retrying { in_secs: 0 };
                        final_state
                            .notes
                            .push(format!("max_tokens {prev} did not fit the context window; retrying with {v}"));
                        final_state.done = true;
                        view.finish(final_state).await;
                        return Outcome::Shrink(v);
                    }
                }
                let failed_now = failed_before + 1;
                let delay = backoff(app, failed_now, &e);
                let will_retry = !append_mode && delay.is_some() && failed_now < ctx.max_attempts;
                final_state.error = Some(e.clone());
                final_state.status = match (will_retry, delay) {
                    (true, Some(d)) => Status::Retrying { in_secs: d.as_secs() },
                    _ => Status::Failed,
                };
                final_state.done = true;
                view.finish(final_state).await;
                if will_retry { Outcome::Retry(delay.unwrap()) } else { Outcome::Failed }
            }
        }
    }
    .instrument(attempt_span)
    .await
}

/// The latest text message of a turn, not counting attempt `except`'s own.
async fn last_message_of_turn(app: &App, turn_id: i64, except: i64) -> Option<i32> {
    app.db
        .call(move |c| {
            Ok(c.query_row(
                "SELECT msg_id FROM tg_messages WHERE turn_id = ?1 AND part_index >= 0 AND part_index < 1000
                   AND (attempt_id IS NULL OR attempt_id != ?2) ORDER BY msg_id DESC LIMIT 1",
                params![turn_id, except],
                |r| r.get(0),
            )
            .optional()?)
        })
        .await
        .ok()
        .flatten()
}

async fn save_echo(app: &App, attempt_id: i64, echo: Value) -> Result<()> {
    let s = echo.to_string();
    app.db
        .call(move |c| {
            c.execute(
                "UPDATE attempts SET request = json_set(COALESCE(request, '{}'), '$.upstream_echo', json(?1)) WHERE id = ?2",
                params![s, attempt_id],
            )?;
            Ok(())
        })
        .await
}

/// A turn that fails before any upstream call (bad options, quota, failed parent...).
async fn fail_without_attempt(ctx: &Ctx, err: LlmError) -> Result<()> {
    let app = &ctx.app;
    warn!(error = %err, "turn failed before calling the model");
    let attempt = conv::start_attempt(&app.db, ctx.turn_id, &json!({"not_sent": true})).await?;
    conv::update_attempt(
        &app.db,
        attempt.id,
        AttemptUpdate {
            status: "failed",
            output: None,
            error: serde_json::to_value(&err).ok(),
            upstream_id: None,
            usage: None,
            finished: true,
        },
    )
    .await?;
    let mut st = ctx.base_state.clone();
    st.attempt = attempt.n;
    st.error = Some(err);
    st.status = Status::Failed;
    st.elapsed_override = Some(Duration::ZERO);
    let view = ReplyView::start(
        app.clone(),
        ctx.bot.clone(),
        ctx.chat_id,
        ctx.reply_to,
        ctx.turn_id,
        attempt.id,
        Duration::ZERO,
    );
    view.finish(st).await;
    conv::set_turn_status(&app.db, ctx.turn_id, TurnStatus::Failed).await?;
    Ok(())
}

async fn send_images(
    app: &Arc<App>,
    bot: &Arc<BotConn>,
    chat_id: i64,
    reply_to: Option<i32>,
    turn_id: i64,
    attempt_id: i64,
    turn: &Turn,
) {
    let mut idx = 0i64;
    for p in &turn.parts {
        if let Part::Image { blob, generated: true, .. } = p {
            idx += 1;
            let Ok(bytes) = app.blobs.get(blob).await else { continue };
            let ext = blob.mime.rsplit('/').next().unwrap_or("png");
            let name = format!("image-{turn_id}-{idx}.{ext}");
            let link = Link { turn_id, attempt_id: Some(attempt_id), part_index: 1000 + idx };
            let res =
                outbox::send_file(&app.db, bot, chat_id, reply_to, bytes.clone(), &name, &blob.mime, true, "", link)
                    .await;
            if let Err(e) = res {
                warn!(error = %e, "sending image as photo failed; sending as file");
                let link = Link { turn_id, attempt_id: Some(attempt_id), part_index: 2000 + idx };
                if let Err(e) =
                    outbox::send_file(&app.db, bot, chat_id, reply_to, bytes, &name, &blob.mime, false, "", link).await
                {
                    warn!(error = %e, "sending image failed");
                }
            }
        }
    }
}

