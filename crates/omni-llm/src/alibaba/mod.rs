//! Alibaba Cloud Model Studio / Bailian (DashScope), China (Beijing) region,
//! OpenAI-compatible mode at `https://dashscope.aliyuncs.com/compatible-mode/v1`
//! (the old bot's URL; Alibaba now recommends the workspace domain
//! `https://{WorkspaceId}.cn-beijing.maas.aliyuncs.com/compatible-mode/v1`,
//! which can be configured as the base URL). Spec:
//! docs/research/glm_kimi_qwen.md §3, checked against help.aliyun.com/zh/model-studio
//! on 2026-11-12.
//!
//! - **Chat Completions** (`alibaba.chat`) for every request without a tool.
//!   Thinking is hybrid (`enable_thinking`, on by default, sent explicitly);
//!   Qwen3.8 adds `reasoning_effort` low | medium | xhigh, sent explicitly as
//!   xhigh (unset, the thinking budget is 131,072 instead of xhigh's 262,144);
//!   `budget=` maps to `thinking_budget`.
//! - **Web search and the code interpreter** (`+s`, `+c`, together too, and
//!   `+su` with the web extractor): the Responses API (`alibaba.responses`, see
//!   [`responses`]) with `store: false` and its `web_search`,
//!   `code_interpreter` and `web_extractor` tools. Chat Completions' search
//!   (`enable_search`) returns no sources ("OpenAI 兼容协议因协议限制，不支持
//!   搜索来源返回"), only a count, and the code interpreter there is only for
//!   the Qwen3-Max and Qwen3.5-Plus series; on Responses every search is a
//!   `web_search_call` with its query and sources (which become the answer's
//!   sources). The Responses search is agent-style: the model decides whether
//!   and how often to search (`search_strategy` does not apply there), billed
//!   like the `agent` strategy. What that API lacks is an error or a note: no
//!   `thinking_budget` (`budget=` is an error), no high-resolution image switch
//!   (noted), videos only as public URLs (an error), and only about 80% of the
//!   window is kept (a longer conversation is an error instead of being
//!   silently truncated).
//! - `reasoning_content` is replayed for the same model (Qwen3.8 reads it back by
//!   default: `preserve_thinking` defaults to true there). Assistant messages
//!   carry text only (on both APIs): media generated by other models in earlier
//!   turns are not sent (a warning says what).
//! - Images and videos as base64 data URLs, images at the highest resolution
//!   (`vl_high_resolution_images`). PDFs and documents only go through
//!   uploads/URLs (Qwen-Long `fileid://`, Responses `input_file` URLs): rejected.
//! - Output: the default `max_completion_tokens` is the model's maximum and the
//!   input has its own limit, so no output budget is sent unless a cap is
//!   configured.
//! - Errors: `{"error":{"message","type","param","code"},"request_id"}` (DashScope
//!   style `{"code","message","request_id"}` on some paths); moderation
//!   (`data_inspection_failed`) may be triggered by the input or the output.
//! - No cost in responses: estimated from the CNY price list (Beijing), plus
//!   the billed searches (`tool_usage.web_search.num_requests`).
//!
//! The image models (Qwen-Image, Wan, Z-Image) use DashScope's own image API
//! ([`images`]), the video models (HappyHorse, Wan) its asynchronous video API
//! ([`video`]).

