/// Estimated cost in USD: tokens at the CNY list price of the request's input
/// tier (cache hits at their price, output incl. reasoning) plus web searches
/// ([`WEB_SEARCH_CNY`] each).
pub fn estimate_cost(spec: &ModelSpec, u: &Usage, searches: u64, cny_per_usd: f64) -> Option<f64> {
    let input = u.input_tokens?;
    let tier = spec.tiers.iter().find(|t| input <= t.up_to).or_else(|| spec.tiers.last())?;
    let tokens = tier.price.cost(u)?;
    usd(tokens + searches as f64 * WEB_SEARCH_CNY, Currency::Cny, cny_per_usd)
}

